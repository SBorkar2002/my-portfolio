// Copies the cat sprite frames from the cat studio export into lib/cat/frames.ts.
// Usage: node scripts/export-cat-frames.mjs <path to cat-v2/preview/frames.json>
// The cat studio owns the art (cat-v2/sprites.py renders frames.json); this only reads it.
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/export-cat-frames.mjs <frames.json>");
  process.exit(1);
}

// Fall is used when the cat drops into a section.
const STATES = ["Sit", "Idle", "Walk", "Look", "Inspect", "Yawn", "Sleep", "Peek", "React", "Fall", "Land"];
const data = JSON.parse(readFileSync(src, "utf8"));

const frames = {};
const timings = {};
for (const state of STATES) {
  // Trailing transparent pixels are dropped from each row to keep the file small.
  frames[state] = data.frames[state].map((rows) => rows.map((row) => row.replace(/\.+$/, "")));
  timings[state] = data.timings[state];
}

const out = `// Generated by scripts/export-cat-frames.mjs from the cat studio's frames.json. Do not edit by hand.
// 48 x 48 palette-indexed frames. Legend: '.' empty, '#' body, 'f' far legs, 'Y' eye ring, 'p' pupil,
// 'w' eye shine, 'm' mouth, 'M' mouth inner, 'z' Z, 'h' heart. Rows end early where the rest is empty.
export const SIZE = ${data.size};

export const frames = ${JSON.stringify(frames)} as const;

/** Seconds each frame holds before the next. */
export const timings = ${JSON.stringify(timings)} as const;

export type CatState = keyof typeof frames;
`;
writeFileSync("lib/cat/frames.ts", out);
console.log("wrote lib/cat/frames.ts", Object.entries(frames).map(([k, v]) => `${k}:${v.length}`).join(" "), `${Math.round(out.length / 1024)}KB`);
